"""Reviewed fx16 what-if goldens (tests/golden/fx16-*).

The goldens were reviewed by hand against the intervention rules; they are never
regenerated to make a test pass. The only normalised value is the source report digest,
which depends on the analyzer identity (tool version, rules and data digests).
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pytest
import typer
from typer.testing import CliRunner

from nhi_blast.cli.whatif_cmd import whatif
from tests.test_whatif_support import FORBIDDEN, GOLDEN, fx16_report, save

app = typer.Typer()
app.command("whatif")(whatif)


@app.command("noop")
def _noop() -> None:
    """Keeps typer in multi-command mode so that the subcommand name is required."""


CASES = {
    "full": GOLDEN / "fx16-plan-full.json",
    "revoke": GOLDEN / "fx16-plan-revoke.yaml",
}
DIGEST = "<source-report-digest>"


@pytest.fixture(scope="module")
def report_file(tmp_path_factory: pytest.TempPathFactory) -> Path:
    return save(fx16_report(), tmp_path_factory.mktemp("golden") / "report.json")


def _run(report_file: Path, plan: Path, out: Path) -> tuple[dict[str, object], str]:
    result = CliRunner().invoke(
        app, ["whatif", str(report_file), "--plan", str(plan), "--out", str(out)]
    )
    assert result.exit_code == 0, result.stderr
    document = json.loads((out / "whatif.json").read_text(encoding="utf-8"))
    markdown = (out / "playbook.md").read_text(encoding="utf-8")
    assert document["source_report_digest"] != DIGEST
    document["source_report_digest"] = DIGEST
    markdown = re.sub(r"(Source report digest: )`[0-9a-f]{64}`", rf"\1`{DIGEST}`", markdown)
    return document, markdown


@pytest.mark.golden
@pytest.mark.parametrize("case", sorted(CASES))
def test_json_and_playbook_match_the_reviewed_goldens(
    report_file: Path, tmp_path: Path, case: str
) -> None:
    document, markdown = _run(report_file, CASES[case], tmp_path)
    expected_json = GOLDEN / f"fx16-whatif-{case}.json"
    expected_md = GOLDEN / f"fx16-playbook-{case}.md"
    assert expected_json.is_file(), "goldens are reviewed files and are never generated by tests"
    assert document == json.loads(expected_json.read_text(encoding="utf-8"))
    assert markdown == expected_md.read_text(encoding="utf-8")


@pytest.mark.golden
@pytest.mark.parametrize("case", sorted(CASES))
def test_goldens_follow_the_language_and_header_rules(case: str) -> None:
    text_json = (GOLDEN / f"fx16-whatif-{case}.json").read_text(encoding="utf-8")
    text_md = (GOLDEN / f"fx16-playbook-{case}.md").read_text(encoding="utf-8")
    assert FORBIDDEN.search(text_json) is None
    assert FORBIDDEN.search(text_md) is None
    assert text_md.splitlines()[0] == "Offline model. Not executed. Verify in your account."
    assert json.loads(text_json)["header"] == "Offline model. Not executed. Verify in your account."
    assert re.search(r"\bexpired\b", text_json + text_md) is None
    assert "ghp_" not in text_json + text_md
